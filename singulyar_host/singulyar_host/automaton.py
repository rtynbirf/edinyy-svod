# --- Журнал автомата ---------------------------------------------------------
@dataclass(frozen=True)
class MachineRecord:
    seq: int
    state: str                 # голова до события
    event: str                 # предъявленное событие
    verdict: str               # ПЕРЕХОД | ЗАПРЕТ | НЕИЗВЕСТНОЕ_СОБЫТИЕ
    to_state: Optional[str]    # новое состояние (только ПЕРЕХОД)
    note: str                  # основание или причина запрета


def fold(records: List[MachineRecord]) -> str:
    """Состояние — свёртка журнала (Raft/Event Sourcing, Ф-X-1, Х-063)."""
    state = "НЕ ПРОВЕРЕНО"
    for r in records:
        if r.verdict == "ПЕРЕХОД":
            state = r.to_state or state
    return state


class HouseAutomaton:
    """
    Конечный автомат дома. Единственный законный способ изменить голову —
    step(): событие сверяется с таблицей, исход пишется в журнал.
    Прямой записи состояния нет — правка без события есть подмена (Х-063).
    """

    def __init__(self) -> None:
        self._records: List[MachineRecord] = []

    # -- чтение ---------------------------------------------------------------
    @property
    def head(self) -> str:
        return fold(self._records)

    @property
    def journal(self) -> List[MachineRecord]:
        return list(self._records)

    # -- ход ------------------------------------------------------------------
    def step(self, state: str, event: str) -> MachineRecord:
        """Применить событие к названной голове; исход — новой записью."""
        if state != self.head and self._records:
            raise ValueError("подмена головы: событие предъявлено не к текущему состоянию")
        if event not in EVENTS:
            rec = MachineRecord(len(self._records) + 1, state, event,
                                "НЕИЗВЕСТНОЕ_СОБЫТИЕ", None,
                                "Ф-X-2: событие вне таблицы — запрет и запись попытки")
            self._records.append(rec)
            return rec
        move = TRANSITIONS.get((state, event))
        if move is not None:
            rec = MachineRecord(len(self._records) + 1, state, event,
                                "ПЕРЕХОД", move[0], move[1])
        else:
            f = _refusal(state, event)
            rec = MachineRecord(len(self._records) + 1, state, event,
                                "ЗАПРЕТ", None, f"{f.name}: {f.reason}")
        self._records.append(rec)
        return rec

    # -- проверки автомата (Ф-X-5) ---------------------------------------------
    def coverage(self) -> Dict[str, int]:
        """Полнота таблицы: каждая пара (состояние, событие) покрыта."""
        holes: List[Tuple[str, str]] = []
        for s in STATES:
            for e in EVENTS:
                if (s, e) not in TRANSITIONS:
                    try:
                        f = _refusal(s, e)
                    except AssertionError:
                        holes.append((s, e))
        return {
            "клеток": len(STATES) * len(EVENTS),
            "переходов": len(TRANSITIONS),
            "запретов": len(STATES) * len(EVENTS) - len(TRANSITIONS) - len(holes),
            "дыр": len(holes),
        }

    def reachability(self) -> Dict[str, object]:
        """Полный обход достижимых состояний (Ф-X-5, Х-064)."""
        seen = {"НЕ ПРОВЕРЕНО"}
        frontier = ["НЕ ПРОВЕРЕНО"]
        while frontier:
            cur = frontier.pop()
            for e in EVENTS:
                nxt = TRANSITIONS.get((cur, e))
                if nxt is not None and nxt[0] not in seen:
                    seen.add(nxt[0])
                    frontier.append(nxt[0])
        return {
            "достижимых": len(seen),
            "всего": len(STATES),
            "мёртвые": [s for s in STATES if s not in seen],
            "порядок": sorted(seen),
        }
